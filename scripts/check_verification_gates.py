#!/usr/bin/env python3
"""Offline verification gates for dependency security, API documentation, and archived docs.

Run from the repository root:

    python scripts/check_verification_gates.py
    python scripts/check_verification_gates.py --only api-doc

Gates
-----
lockfile   Dependency security floors plus manifest/lock agreement. Prevents the
           advisories closed for fastmcp (CVE-2026-32871) and fast-uri
           (CVE-2026-13676) from silently regressing on a future lock refresh.
api-doc    Every action the mod accepts in POST /action must appear in the
           action contract block in docs/api.md, and the block must not list
           actions the code no longer supports.
api-facts  Facts that docs/api.md states and that code owns must still agree:
           the documented `mod_version` against mod_manifest.json, the screen
           enum against the screens GameStateService.ResolveNonModalScreen can
           emit, the documented default port against HttpServer.DefaultPort, and
           the /state payload surface against the docs/api.md tables that
           describe it. Sixteen payload records are checked field-for-field
           against their own table, every action_readiness reason code
           EvaluateCombatActionGate can answer with must be documented, the
           compact agent_view rename table must match the renames the
           BuildAgent*Payload methods actually perform, and under all of it sits
           a coarse net: every serialized field of every /state payload record
           has to be named somewhere in docs/api.md.
           The action contract only covers action names, so all of this would
           otherwise drift silently -- which is what happened. 91 fields across
           23 records had shipped with no mention anywhere a client could read,
           including whole screens an agent has to drive (character_select,
           multiplayer_lobby, game_over) and the session block the play skill
           tells agents to route on first.
doc-marks  Date-stamped validation records must carry a historical marker, and
           archived topic pages must keep their redirect to history/.
docs-tracked
           Every Markdown page under docs/ must be tracked by git. docs/ used to
           be gitignored, so a new page could be written, pass the local
           doc-marks gate, and still be missing from every fresh checkout --
           which is what CI builds from.
packaged-links
           Every local link in a packaged document (README.md, README.zh-CN.md,
           mcp_server/README.md) must resolve inside the release artifact. The
           relative ones are rewritten to absolute URLs by the hand-kept table in
           package-release.ps1, so a newly added relative link could ship
           unrewritten and only fail the artifact check after packaging.
script-encoding
           PowerShell scripts containing non-ASCII text must carry a UTF-8 BOM.
ps1-syntax Every PowerShell script under scripts/ must parse without a syntax error.
           Each one is a build, packaging, validation, or CI entry point that nothing
           else compiles, so a stray brace or quote would only surface when a release
           or a real-machine run finally invoked it. Parsing goes through the
           PowerShell AST parser, which reads a script without executing it. Skips
           with a note when scripts/ holds no .ps1 or no interpreter is on PATH.

Exit code 0 means every selected gate passed. Exit code 1 means at least one
gate failed and the failure detail has been printed to stderr. Standard library
only: preflight invokes this with the system Python.
"""
